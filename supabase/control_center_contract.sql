-- Client RPCs for real two-way support chat. They identify the client by installation_id
-- and only expose that installation's own conversation.
create or replace function public.myplan_send_support_message(
  p_installation_id text, p_user_id uuid, p_body text
) returns bigint language plpgsql security definer set search_path = public
as $$
declare v_conversation uuid; v_id bigint;
begin
  if coalesce(trim(p_body),'') = '' then raise exception 'empty message'; end if;
  select id into v_conversation from public.support_conversations
    where installation_id=p_installation_id and status='open'
    order by updated_at desc limit 1;
  if v_conversation is null then
    insert into public.support_conversations(user_id,installation_id) values(p_user_id,p_installation_id)
    returning id into v_conversation;
  else
    update public.support_conversations set user_id=coalesce(p_user_id,user_id),updated_at=now(),last_message_at=now()
      where id=v_conversation;
  end if;
  insert into public.support_messages(conversation_id,sender_type,sender_user_id,body,delivered_at)
    values(v_conversation,'user',p_user_id,p_body,now()) returning id into v_id;
  update public.support_conversations set updated_at=now(),last_message_at=now() where id=v_conversation;
  return v_id;
end $$;

create or replace function public.myplan_get_support_messages(
  p_installation_id text
) returns setof public.support_messages
language sql security definer set search_path = public
as $$
  select sm.* from public.support_messages sm
  join public.support_conversations sc on sc.id=sm.conversation_id
  where sc.installation_id=p_installation_id
  order by sm.created_at asc
  limit 200;
$$;

create or replace function public.myplan_mark_support_read(
  p_installation_id text
) returns integer language plpgsql security definer set search_path = public
as $$
declare n integer;
begin
  update public.support_messages sm set read_at=coalesce(read_at,now())
  from public.support_conversations sc
  where sc.id=sm.conversation_id and sc.installation_id=p_installation_id
    and sm.sender_type='admin' and sm.read_at is null;
  get diagnostics n = row_count;
  return n;
end $$;

