-- Admin authorization helper. Control Center actions must use Supabase Auth + this table.
create or replace function public.cc_is_admin(required_role text default null)
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.admins a
    where a.user_id = auth.uid() and a.enabled = true
      and (required_role is null or a.role in ('owner','admin',required_role))
  );
$$;

-- Secure admin RPCs. No service_role key belongs in the Android APK or browser.
create or replace function public.cc_grant_premium(
  p_user_id uuid, p_expires_at timestamptz, p_grant_type text default 'manual',
  p_source text default 'control_center', p_feature_keys jsonb default '[]'::jsonb, p_note text default null
) returns uuid language plpgsql security definer set search_path = public
as $$ declare v_id uuid;
begin
  if not public.cc_is_admin('admin') then raise exception 'not authorized'; end if;
  insert into public.premium_grants(user_id,status,grant_type,source,expires_at,feature_keys,note)
  values(p_user_id,'active',p_grant_type,p_source,p_expires_at,p_feature_keys,p_note) returning id into v_id;
  insert into public.admin_activity_log(admin_id,action,target_type,target_id,new_state)
  values(auth.uid(),'premium.grant','user',p_user_id::text,jsonb_build_object('grant_id',v_id,'expires_at',p_expires_at));
  return v_id;
end $$;

create or replace function public.cc_revoke_premium(p_grant_id uuid, p_reason text default null)
returns boolean language plpgsql security definer set search_path = public
as $$ begin
  if not public.cc_is_admin('admin') then raise exception 'not authorized'; end if;
  update public.premium_grants set status='revoked',updated_at=now(),note=coalesce(p_reason,note) where id=p_grant_id;
  return found;
end $$;

create or replace function public.cc_set_remote_config(p_key text,p_value jsonb,p_type text default 'json',p_description text default null,p_enabled boolean default true)
returns boolean language plpgsql security definer set search_path = public
as $$ begin
  if not public.cc_is_admin('admin') then raise exception 'not authorized'; end if;
  insert into public.remote_config(config_key,config_value,value_type,description,enabled,updated_by)
  values(p_key,p_value,p_type,p_description,p_enabled,auth.uid())
  on conflict(config_key) do update set config_value=excluded.config_value,value_type=excluded.value_type,description=excluded.description,enabled=excluded.enabled,updated_at=now(),updated_by=auth.uid();
  insert into public.admin_activity_log(admin_id,action,target_type,target_id,new_state) values(auth.uid(),'remote_config.set','config',p_key,p_value);
  return true;
end $$;

create or replace function public.cc_set_maintenance(p_enabled boolean,p_message text default null,p_starts_at timestamptz default null,p_ends_at timestamptz default null)
returns boolean language plpgsql security definer set search_path = public
as $$ begin
  if not public.cc_is_admin('admin') then raise exception 'not authorized'; end if;
  insert into public.maintenance_controls(id,enabled,message,starts_at,ends_at,updated_at) values(true,p_enabled,p_message,p_starts_at,p_ends_at,now())
  on conflict(id) do update set enabled=excluded.enabled,message=excluded.message,starts_at=excluded.starts_at,ends_at=excluded.ends_at,updated_at=now();
  return true;
end $$;

